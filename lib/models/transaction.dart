import 'package:equatable/equatable.dart';
import 'package:fin_pay/core/money/money.dart';

/// The direction/category of a transaction.
enum TransactionType {
  payment,
  sendMoney,
  receiveMoney,
  topUp;

  /// Parses both the short name (`payment`) and the legacy `toString()` form
  /// (`TransactionType.payment`). Unknown values become [payment].
  static TransactionType parse(String? value) {
    final name = value?.split('.').last;
    return TransactionType.values.firstWhere(
      (e) => e.name == name,
      orElse: () => TransactionType.payment,
    );
  }
}

/// A money movement on the account. Immutable value type.
///
/// [date] is always stored in UTC; use [localDate] for display and grouping.
/// [idempotencyKey] is generated by the client when the user confirms a
/// payment, so the same confirmation submitted twice creates one row.
class Transaction extends Equatable {
  Transaction({
    required this.id,
    required this.title,
    required this.amount,
    required DateTime date,
    required this.type,
    required this.icon,
    this.recipient,
    String? idempotencyKey,
  }) : date = date.toUtc(),
       idempotencyKey = idempotencyKey ?? id;

  /// Reads a transaction from JSON written by [toJson] (or a sqflite row).
  factory Transaction.fromJson(Map<String, dynamic> json) {
    return Transaction(
      id: json['id'] as String,
      title: json['title'] as String,
      amount: Money.fromJson(json['amount']),
      date: DateTime.parse(json['date'] as String),
      type: TransactionType.parse(json['type'] as String?),
      icon: json['icon'] as String? ?? '',
      recipient: json['recipient'] as String?,
      idempotencyKey: json['idempotencyKey'] as String?,
    );
  }

  final String id;
  final String title;
  final Money amount;
  final DateTime date;
  final TransactionType type;
  final String icon;
  final String? recipient;
  final String idempotencyKey;

  /// The transaction instant in the device's local time zone.
  DateTime get localDate => date.toLocal();

  /// True when money came in.
  bool get isCredit => amount.isPositive;

  Transaction copyWith({
    String? id,
    String? title,
    Money? amount,
    DateTime? date,
    TransactionType? type,
    String? icon,
    String? recipient,
    bool clearRecipient = false,
    String? idempotencyKey,
  }) {
    return Transaction(
      id: id ?? this.id,
      title: title ?? this.title,
      amount: amount ?? this.amount,
      date: date ?? this.date,
      type: type ?? this.type,
      icon: icon ?? this.icon,
      recipient: clearRecipient ? null : (recipient ?? this.recipient),
      idempotencyKey: idempotencyKey ?? this.idempotencyKey,
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'amount': amount.toJson(),
    'date': date.toIso8601String(),
    'type': type.name,
    'icon': icon,
    'recipient': recipient,
    'idempotencyKey': idempotencyKey,
  };

  @override
  List<Object?> get props => [
    id,
    title,
    amount,
    date,
    type,
    icon,
    recipient,
    idempotencyKey,
  ];
}
